<?php

declare(strict_types=1);

namespace Ramjet\Theme\Console;

use Illuminate\Console\Command;
use Illuminate\Mail\Markdown;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Facades\View;
use Ramjet\Theme\Email\PreviewNotifications;

/**
 * Writes every notification email to a directory, as the HTML the panel would send and the plain text it would
 * send beside it. Nothing is mailed and nothing is written to the database.
 */
final class EmailPreviewCommand extends Command
{
    protected $signature = 'ramjet-theme:email-preview
        {directory : Directory to write the previews into (created if missing)}
        {--inline-logo : Embed the emblem as data: URIs so the previews render without the panel reachable}';

    protected $description = 'Render every notification email (HTML and plain text) to a directory. Sends nothing.';

    public function handle(): int
    {
        $directory = rtrim((string) $this->argument('directory'), '/\\');
        File::ensureDirectoryExists($directory);

        if ($this->option('inline-logo')) {
            View::share('ramjetEmailLogo', $this->inlineLogo());
        }

        $index = [];
        foreach (PreviewNotifications::samples() as $sample) {
            $message = $sample['notification']->toMail($sample['notifiable']);

            $html = $message->render();
            $text = app(Markdown::class)->theme(config('mail.markdown.theme', 'default'))
                ->renderText($message->markdown, $message->data());

            File::put($directory.DIRECTORY_SEPARATOR.$sample['slug'].'.html', (string) $html);
            File::put($directory.DIRECTORY_SEPARATOR.$sample['slug'].'.txt', (string) $text);

            $index[] = $sample;
            $this->components->info("Wrote {$sample['slug']}.html and {$sample['slug']}.txt");
        }

        File::put($directory.DIRECTORY_SEPARATOR.'index.html', $this->indexPage($index));
        $this->components->info('Wrote index.html ('.count($index).' emails)');

        return self::SUCCESS;
    }

    /** @return array{src: string, src2x: string} */
    private function inlineLogo(): array
    {
        $resources = dirname(__DIR__, 2).DIRECTORY_SEPARATOR.'resources'.DIRECTORY_SEPARATOR.'email'.DIRECTORY_SEPARATOR;

        return [
            'src' => 'data:image/png;base64,'.base64_encode(File::get($resources.'emblem.png')),
            'src2x' => 'data:image/png;base64,'.base64_encode(File::get($resources.'emblem@2x.png')),
        ];
    }

    /** @param list<array{slug: string, title: string}> $samples */
    private function indexPage(array $samples): string
    {
        $items = '';
        foreach ($samples as $sample) {
            $slug = htmlspecialchars($sample['slug'], ENT_QUOTES, 'UTF-8');
            $title = htmlspecialchars($sample['title'], ENT_QUOTES, 'UTF-8');
            $items .= "<li><strong>{$title}</strong> <a href=\"{$slug}.html\">HTML</a> &middot; <a href=\"{$slug}.txt\">plain text</a></li>\n";
        }

        return <<<HTML
        <!DOCTYPE html>
        <html lang="en">
        <head>
            <meta charset="utf-8">
            <meta name="viewport" content="width=device-width, initial-scale=1">
            <title>Ramjet email previews</title>
            <style>
                body { margin: 0; padding: 32px 16px; background: #0a0b0d; color: #eceef1; font-family: Archivo, "Helvetica Neue", Helvetica, Arial, sans-serif; }
                main { max-width: 640px; margin: 0 auto; }
                h1 { font-size: 24px; margin: 0 0 8px; }
                p { color: #9aa1ac; line-height: 1.6; }
                li { margin: 10px 0; }
                a { color: #ff9a52; }
            </style>
        </head>
        <body>
            <main>
                <h1>Ramjet email previews</h1>
                <p>Each email as the panel sends it (HTML), and its plain-text part. Generated by <code>ramjet-theme:email-preview</code>.</p>
                <ul>
                    {$items}
                </ul>
            </main>
        </body>
        </html>

        HTML;
    }
}
